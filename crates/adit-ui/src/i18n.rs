//! UI language.
//!
//! Lookup is by the Chinese source string, and anything missing falls back to
//! it. Every string in this program was written in Chinese first, so English is
//! a translation of it rather than the other way round — which means a missing
//! entry shows the original instead of a bare key, and the table can grow
//! without touching a single call site.

use std::collections::HashMap;
use std::sync::{
    atomic::{AtomicU8, Ordering},
    OnceLock,
};

use adit_storage::Language;

mod runtime;
#[cfg(test)]
mod tests;

/// Read on every drawn string, written once when the setting changes. An atomic
/// rather than a field on `AditApp` because the alternative is threading a
/// language through every widget helper in the crate for a value that never
/// differs between them.
static LANGUAGE: AtomicU8 = AtomicU8::new(0);

pub(crate) fn set_language(language: Language) {
    LANGUAGE.store(u8::from(language == Language::En), Ordering::Relaxed);
}

/// Translate one UI string, or hand it back unchanged.
#[must_use]
pub(crate) fn t(zh: &str) -> &str {
    t_in("", zh)
}

/// Context-specific wording, then the common catalog, then the source itself.
/// Contexts describe UI roles; Chinese source text remains the lookup key.
#[must_use]
pub(crate) fn t_in<'a>(context: &str, zh: &'a str) -> &'a str {
    translate(LANGUAGE.load(Ordering::Relaxed) != 0, context, zh)
}

fn translate<'a>(english: bool, context: &str, zh: &'a str) -> &'a str {
    if !english {
        return zh;
    }
    static COMMON_INDEX: OnceLock<HashMap<&str, &str>> = OnceLock::new();
    CONTEXTUAL
        .iter()
        .find(|(c, source, _)| *c == context && *source == zh)
        .map(|(_, _, en)| *en)
        .or_else(|| {
            COMMON_INDEX
                .get_or_init(|| COMMON.iter().copied().collect())
                .get(zh)
                .copied()
        })
        .unwrap_or(zh)
}

/// Localise application diagnostics at the GUI boundary. Unknown diagnostics
/// and captured user/server values are preserved; terminal output never enters
/// this adapter. Only explicitly named `{error}` slots recurse.
pub(crate) fn runtime(message: &(impl std::fmt::Display + ?Sized)) -> String {
    runtime::render(LANGUAGE.load(Ordering::Relaxed) != 0, &message.to_string())
}

/// Translate a template, then fill its holes in order.
///
/// `format!` needs a literal and a translated template is a runtime value, so
/// the substitution has to happen here. Holes are positional and unnamed on
/// purpose: a translator can move the words around them freely but not the
/// values, which is the trade that keeps this a dozen lines instead of a
/// dependency.
#[must_use]
pub(crate) fn tf(zh: &'static str, args: &[&dyn std::fmt::Display]) -> String {
    tf_in("", zh, args)
}

#[must_use]
pub(crate) fn tf_in(context: &str, zh: &str, args: &[&dyn std::fmt::Display]) -> String {
    fill(t_in(context, zh), args)
}

fn fill(template: &str, args: &[&dyn std::fmt::Display]) -> String {
    let mut out = String::with_capacity(template.len() + 16);
    let mut rest = template;
    for arg in args {
        match rest.find("{}") {
            Some(at) => {
                out.push_str(&rest[..at]);
                out.push_str(&arg.to_string());
                rest = &rest[at + 2..];
            }
            // More values than holes: a translation dropped one. Appending it
            // beats losing it without a word.
            None => out.push_str(&arg.to_string()),
        }
    }
    out.push_str(rest);
    out
}

